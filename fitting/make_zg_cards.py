    parser.add_argument("--tag", help="tag", type=str, required=True)
    parser.add_argument(
        "--indir", help="Input dir containing fitting_*.root", type=str, required=True
    )
    parser.add_argument(
        "--order", help="Polynomial order for DataResidual (pt, rho)", type=int, default=0
    )

    args = parser.parse_args()
    zgamma_rhalphabet(args)
